# Numbers:
    # Integer (int):
    # A number without decimal point.
    # including zero.
    # Integers can be +ve and -ve
    # Ex: 8, 123, 900, 45, -1, 0,-345, -500

num1 = 23
print(num1, type(num1))   #  <class 'int'>

num2 = 0
print(num2, type(num2))   #  <class 'int'>

num3 = -123
print(num3, type(num3))   #  <class 'int'>

#-------------------------------------------------

    # Float (float):
    # A number with decimal point.
    # Float  can be +ve and -ve
    # Ex: 90.00, 23.987, 0.00, 0.123, -0.123, -456.500, -100.209
num4 = 90.00
print(num4, type(num4))  # <class 'float'>
num5 = 0.00
print(num5, type(num5))  # <class 'float'>
num6 = -0.123
print(num6, type(num6))  # <class 'float'>
num7 = -340.156789
print(num7, type(num7))  # <class 'float'>

    # Complex (complex):
    # A complex number is a combination of real number and imaginary number.
    # What is real number:
        # All Intgers and Floats are real numbers.
        # Ex: 34, 90.123, -0.00, -36.98, -120

    # What is imaginary number:
        # An Imaginary number is always suffixed by "j"
        # Ex: 89j, -123j, 0.12j, -89.234j

    # Ex of Complex:
        # 78+56j, -12-45j, -4+12j, 9.67j-123j, 8+7.45j

num8 = 78+56j
print(num8, type(num8))   #<class 'complex'>


